// server/api/admin/cmoons.get.js
import { defineEventHandler } from 'h3'
import { prisma as db } from '@/server/prisma'
import { requireAdmin } from '@/server/utils/requireAdmin'

export default defineEventHandler(async (event) => {
  await requireAdmin(event)

  const [cmoons, config] = await Promise.all([
    db.cMoon.findMany({
      orderBy: { createdAt: 'asc' },
      include: {
        customJoinEffect: true,
        specialAttack: true,
        captains: { include: { user: { select: { id: true, username: true } } } },
        prizeCtoons: { include: { ctoon: { select: { id: true, name: true, assetPath: true } } } },
        ranks: { orderBy: { sortOrder: 'asc' } },
        poll: { select: { question: true, options: { select: { label: true }, orderBy: { sortOrder: 'asc' } } } },
        affinityLevels: {
          orderBy: { sortOrder: 'asc' },
          include: {
            borderEffect: true,
            glowEffect: true,
            rewardBackground: { select: { id: true, label: true, imagePath: true } },
            rewardAvatars: { include: { avatar: { select: { id: true, label: true, imagePath: true } } } },
          },
        },
        // Single grouped query, not a per-cMoon count() loop.
        _count: { select: { displayedCtoons: true } },
      },
    }),
    db.globalGameConfig.findUnique({
      where: { id: 'singleton' },
      select: {
        cMoonEnabled: true, cMoonEnabledAt: true, cMoonOptOutCooldownDays: true,
        cMoonEnemyBattlesEnabled: true,
        cMoonBattlePopupChancePercent: true, cMoonBattlePopupCooldownMinutes: true,
        cMoonEnemySpawnCapCount: true, cMoonEnemySpawnCapWindowHours: true,
        cMoonRaidBossDiscordChannelId: true, cMoonEnemyBattleDefaultHp: true,
        cMoonEnemyBattleStartingStamina: true, cMoonEnemyBattleBlockCounterDamage: true,
        cMoonEnemyHigherTierFirst: true,
        cMoonTeamMilestoneEnabled: true, cMoonTeamMilestoneEnemiesInterval: true, cMoonTeamMilestonePointsInterval: true,
        cMoonRankUpAnnounceEnabled: true, cMoonRankUpAnnounceMinSortOrder: true,
        cMoonFinalBossPingEnabled: true, cMoonFinalBossPingCooldownMinutes: true,
        cMoonWelcomePostEnabled: true,
        cMoonWeeklyRecapEnabled: true, cMoonWeeklyRecapDayOfWeek: true, cMoonWeeklyRecapHour: true, cMoonWeeklyRecapMinute: true,
        cMoonSeasonMvpRecapEnabled: true,
        cMoonSharedBossDefeatAnnounceEnabled: true,
      },
    }),
  ])

  return {
    cMoonEnabled: !!config?.cMoonEnabled,
    cMoonEnabledAt: config?.cMoonEnabledAt || null,
    cMoonOptOutCooldownDays: config?.cMoonOptOutCooldownDays ?? 14,
    cMoonEnemyBattlesEnabled: !!config?.cMoonEnemyBattlesEnabled,
    cMoonBattlePopupChancePercent: config?.cMoonBattlePopupChancePercent ?? 3,
    cMoonBattlePopupCooldownMinutes: config?.cMoonBattlePopupCooldownMinutes ?? 20,
    cMoonEnemySpawnCapCount: config?.cMoonEnemySpawnCapCount ?? 0,
    cMoonEnemySpawnCapWindowHours: config?.cMoonEnemySpawnCapWindowHours ?? 4,
    cMoonRaidBossDiscordChannelId: config?.cMoonRaidBossDiscordChannelId || '',
    cMoonEnemyBattleDefaultHp: config?.cMoonEnemyBattleDefaultHp ?? 5,
    cMoonEnemyBattleStartingStamina: config?.cMoonEnemyBattleStartingStamina ?? 3,
    cMoonEnemyBattleBlockCounterDamage: config?.cMoonEnemyBattleBlockCounterDamage ?? 1,
    cMoonEnemyHigherTierFirst: !!config?.cMoonEnemyHigherTierFirst,
    cMoonTeamMilestoneEnabled: !!config?.cMoonTeamMilestoneEnabled,
    cMoonTeamMilestoneEnemiesInterval: config?.cMoonTeamMilestoneEnemiesInterval ?? 100,
    cMoonTeamMilestonePointsInterval: config?.cMoonTeamMilestonePointsInterval ?? 1000,
    cMoonRankUpAnnounceEnabled: !!config?.cMoonRankUpAnnounceEnabled,
    cMoonRankUpAnnounceMinSortOrder: config?.cMoonRankUpAnnounceMinSortOrder ?? 0,
    cMoonFinalBossPingEnabled: !!config?.cMoonFinalBossPingEnabled,
    cMoonFinalBossPingCooldownMinutes: config?.cMoonFinalBossPingCooldownMinutes ?? 60,
    cMoonWelcomePostEnabled: !!config?.cMoonWelcomePostEnabled,
    cMoonWeeklyRecapEnabled: !!config?.cMoonWeeklyRecapEnabled,
    cMoonWeeklyRecapDayOfWeek: config?.cMoonWeeklyRecapDayOfWeek ?? 0,
    cMoonWeeklyRecapHour: config?.cMoonWeeklyRecapHour ?? 9,
    cMoonWeeklyRecapMinute: config?.cMoonWeeklyRecapMinute ?? 0,
    cMoonSeasonMvpRecapEnabled: !!config?.cMoonSeasonMvpRecapEnabled,
    cMoonSharedBossDefeatAnnounceEnabled: !!config?.cMoonSharedBossDefeatAnnounceEnabled,
    cmoons: cmoons.map(c => ({
      id: c.id,
      name: c.name,
      color: c.color,
      pageBgColor: c.pageBgColor,
      accentColor: c.accentColor,
      textColor: c.textColor,
      cardBgColor: c.cardBgColor,
      imagePath: c.imagePath,
      avatarPath: c.avatarPath,
      discordRoleId: c.discordRoleId,
      discordChannelId: c.discordChannelId,
      effectType: c.effectType,
      customJoinEffectId: c.customJoinEffectId,
      customJoinEffect: c.customJoinEffect,
      specialAttackId: c.specialAttackId,
      specialAttack: c.specialAttack,
      joinLocked: c.joinLocked,
      showOnNav: c.showOnNav,
      allowOptOutJoin: c.allowOptOutJoin,
      memberCount: c.memberCount,
      pageImagePath: c.pageImagePath,
      pageDescription: c.pageDescription,
      buttonImagePath: c.buttonImagePath,
      showButtonOnPages: c.showButtonOnPages,
      pageBannerImagePath: c.pageBannerImagePath,
      displayedCtoonCount: c._count?.displayedCtoons ?? 0,
      poll: c.poll ? { question: c.poll.question, options: c.poll.options.map(o => o.label) } : null,
      captains: c.captains.map(cap => ({ userId: cap.userId, username: cap.user?.username || '' })),
      prizeCtoons: c.prizeCtoons.map(pc => ({ ctoonId: pc.ctoonId, quantity: pc.quantity, name: pc.ctoon?.name || '', assetPath: pc.ctoon?.assetPath || null })),
      ranks: c.ranks.map(r => ({ id: r.id, name: r.name, sortOrder: r.sortOrder, discordRoleId: r.discordRoleId, tierId: r.tierId })),
      affinityLevels: c.affinityLevels.map(l => ({
        id: l.id, name: l.name, threshold: l.threshold, sortOrder: l.sortOrder,
        borderEffectId: l.borderEffectId, borderEffect: l.borderEffect,
        glowEffectId: l.glowEffectId, glowEffect: l.glowEffect,
        rewardBackgroundId: l.rewardBackgroundId,
        rewardBackground: l.rewardBackground,
        rewardAvatarIds: l.rewardAvatars.map(ra => ra.avatar.id),
        rewardAvatars: l.rewardAvatars.map(ra => ra.avatar),
      })),
    })),
  }
})
